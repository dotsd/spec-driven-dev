"""Generates .specify/memory/architecture/overview.md."""

from __future__ import annotations

from typing import Sequence
from ..models import FileNode, RequirementNode, TicketNode


class OverviewGenerator:
    """Generates the high-level system summary and visual Mermaid topology."""

    def generate(
        self,
        files: dict[str, FileNode],
        file_deps: dict[str, list[str]],
        requirements: Sequence[RequirementNode],
        tickets: Sequence[TicketNode],
        max_diagram_nodes: int = 35,
    ) -> str:
        # Tally languages
        lang_counts: dict[str, int] = {}
        total_routes = 0
        total_models = 0
        for f in files.values():
            lang_counts[f.language] = lang_counts.get(f.language, 0) + 1
            total_routes += len(f.routes)
            total_models += len(f.models)

        sorted_langs = sorted(lang_counts.items(), key=lambda x: x[1], reverse=True)
        lang_summary = ", ".join(f"{lang} ({cnt} files)" for lang, cnt in sorted_langs) or "None detected"

        lines = [
            "# System Architecture: Overview & Topology",
            "",
            "> [!NOTE]",
            "> This document is automatically generated by the Spec Kit Architecture Engine.",
            "> It is continuously maintained as the unified architectural map of the codebase.",
            "",
            "## 1. System Summary & Tech Stack",
            f"- **Languages Detected:** {lang_summary}",
            f"- **Total Source Files Analyzed:** {len(files)}",
            f"- **Total Endpoints & Routes:** {total_routes}",
            f"- **Total Domain Models & Schemas:** {total_models}",
            f"- **Tracked Functional Requirements:** {len(requirements)}",
            f"- **Tracked Work Items / Tickets:** {len(tickets)}",
            "",
            "## 2. Visual System Topology",
            "```mermaid",
            "flowchart TD",
        ]

        def _clean_id(path: str) -> str:
            return "n_" + path.replace("/", "_").replace(".", "_").replace("-", "_")

        # Select top nodes by connectivity
        reverse_deps: dict[str, list[str]] = {}
        for src, dsts in file_deps.items():
            for dst in dsts:
                reverse_deps.setdefault(dst, []).append(src)

        sorted_files = sorted(
            files.keys(),
            key=lambda f: len(file_deps.get(f, [])) + len(reverse_deps.get(f, [])),
            reverse=True,
        )
        key_files = set(sorted_files[:max_diagram_nodes])

        for f in key_files:
            fnode = files[f]
            name = f.split("/")[-1]
            extra = ""
            if fnode.routes:
                extra = f" ⚡ {len(fnode.routes)} routes"
            elif fnode.models:
                extra = f" 📦 {len(fnode.models)} models"
            lines.append(f'    {_clean_id(f)}["{name}{extra}"]')

        added_edges: set[tuple[str, str]] = set()
        for src in key_files:
            for dst in file_deps.get(src, []):
                if dst in key_files:
                    edge = (src, dst)
                    if edge not in added_edges:
                        added_edges.add(edge)
                        lines.append(f"    {_clean_id(src)} --> {_clean_id(dst)}")

        lines.extend([
            "```",
            "",
            "## 3. Architecture Knowledge Categories",
            "Detailed architectural memory is organized across dedicated category documents:",
            "",
            "- [`api-surface.md`](api-surface.md): HTTP/RPC endpoints, CLI commands, and entrypoint handlers.",
            "- [`domain-models.md`](domain-models.md): Database entities, Pydantic/Zod schemas, and data structures.",
            "- [`traceability.md`](traceability.md): Functional PRDs, Spec Kit specifications, and JIRA tickets mapped to code.",
            "- [`dependencies.md`](dependencies.md): Module coupling, dependency graph, and blast radius analysis.",
            "- [`test-map.md`](test-map.md): Test suite mapping, framework conventions, and covered components.",
            "",
        ])

        return "\n".join(lines)
